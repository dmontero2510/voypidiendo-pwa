/*
  VOYPIDIENDO PWA - INSTALACION EN BASE DEL CLIENTE
  Ejecutar dentro de la base comercial correspondiente.
  Compatible con SQL Server 2008 o superior.

  Este archivo crea solamente objetos propios de VoyPidiendo.
  STREMITOS, STREMITOSDET, PADRONPERCE, GSIVAVTA y GSIVADET
  pertenecen al sistema comercial y deben existir previamente.
*/

SET NOCOUNT ON;

/* Identificador idempotente para pedidos creados sin conexión. */
IF COL_LENGTH('dbo.STREMITOS', 'ID_ORIGEN_APP') IS NULL
BEGIN
    ALTER TABLE dbo.STREMITOS ADD ID_ORIGEN_APP varchar(50) NULL;
END;

IF NOT EXISTS
(
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.STREMITOS')
      AND name = 'UX_STREMITOS_ID_ORIGEN_APP'
)
BEGIN
    CREATE UNIQUE INDEX UX_STREMITOS_ID_ORIGEN_APP
        ON dbo.STREMITOS(ID_ORIGEN_APP)
        WHERE ID_ORIGEN_APP IS NOT NULL;
END;
GO

IF OBJECT_ID('dbo.APP_USUARIOS','U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_USUARIOS
    (
        ID_USUARIO int IDENTITY(1,1) NOT NULL,
        USUARIO varchar(50) NOT NULL,
        NOMBRE varchar(100) NOT NULL,
        CLAVE_HASH varchar(100) NOT NULL,
        ROL char(1) NOT NULL,
        HABILITADO bit NOT NULL CONSTRAINT DF_APP_USUARIOS_HABILITADO DEFAULT(1),
        COD_VEND int NULL,
        FECHA_ALTA datetime2(0) NOT NULL CONSTRAINT DF_APP_USUARIOS_FECHA_ALTA DEFAULT(SYSDATETIME()),
        CONSTRAINT PK_APP_USUARIOS PRIMARY KEY(ID_USUARIO),
        CONSTRAINT UX_APP_USUARIOS_USUARIO UNIQUE(USUARIO),
        CONSTRAINT CK_APP_USUARIOS_ROL CHECK(ROL IN('A','V','P','S','Q'))
    );
END;
GO

IF OBJECT_ID('dbo.APP_VISITAS','U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_VISITAS
    (
        ID_VISITA int IDENTITY(1,1) NOT NULL,
        ID_USUARIO int NOT NULL,
        USUARIO varchar(50) NOT NULL,
        ORGANIZACION int NOT NULL,
        COD_CLIENTE int NOT NULL,
        FECHA_LLEGADA datetime NOT NULL CONSTRAINT DF_APP_VISITAS_LLEGADA DEFAULT(GETDATE()),
        LAT_LLEGADA decimal(10,7) NULL,
        LON_LLEGADA decimal(10,7) NULL,
        FECHA_SALIDA datetime NULL,
        LAT_SALIDA decimal(10,7) NULL,
        LON_SALIDA decimal(10,7) NULL,
        CONSTRAINT PK_APP_VISITAS PRIMARY KEY(ID_VISITA),
        CONSTRAINT FK_APP_VISITAS_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES dbo.APP_USUARIOS(ID_USUARIO)
    );
    CREATE INDEX IX_APP_VISITAS_USUARIO_ACTIVA ON dbo.APP_VISITAS(ID_USUARIO,FECHA_SALIDA,FECHA_LLEGADA);
    CREATE INDEX IX_APP_VISITAS_FECHA ON dbo.APP_VISITAS(FECHA_LLEGADA);
END;
GO

IF OBJECT_ID('dbo.APP_CLIENTES_UBICACION','U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_CLIENTES_UBICACION
    (
        ORGANIZACION int NOT NULL,
        COD_CLIENTE int NOT NULL,
        LATITUD decimal(10,7) NOT NULL,
        LONGITUD decimal(10,7) NOT NULL,
        FECHA_REGISTRO datetime NOT NULL CONSTRAINT DF_APP_CLIENTES_UBICACION_FECHA DEFAULT(GETDATE()),
        USUARIO varchar(50) NULL,
        CONSTRAINT PK_APP_CLIENTES_UBICACION PRIMARY KEY(ORGANIZACION,COD_CLIENTE)
    );
END;
GO

IF OBJECT_ID('dbo.APP_TITULO','U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_TITULO
    (
        TITULO varchar(50) NULL,
        SUBTITULO varchar(150) NULL,
        DIRECCION varchar(150) NULL,
        CUIT varchar(20) NULL,
        COMENTARIO varchar(120) NULL,
        TITULO_RUBRO varchar(50) NULL,
        TITULO_MARCA varchar(50) NULL,
        TITULO_ZONA varchar(50) NULL
    );
    INSERT dbo.APP_TITULO(TITULO,SUBTITULO,TITULO_RUBRO,TITULO_MARCA,TITULO_ZONA)
    VALUES('Voy Pidiendo','Toma de pedidos','Rubro','Marca','Zona');
END;
GO

IF COL_LENGTH('dbo.APP_TITULO','DIRECCION') IS NULL ALTER TABLE dbo.APP_TITULO ADD DIRECCION varchar(150) NULL;
IF COL_LENGTH('dbo.APP_TITULO','CUIT') IS NULL ALTER TABLE dbo.APP_TITULO ADD CUIT varchar(20) NULL;
IF COL_LENGTH('dbo.APP_TITULO','COMENTARIO') IS NULL ALTER TABLE dbo.APP_TITULO ADD COMENTARIO varchar(120) NULL;
IF COL_LENGTH('dbo.APP_TITULO','TITULO_RUBRO') IS NULL ALTER TABLE dbo.APP_TITULO ADD TITULO_RUBRO varchar(50) NULL;
IF COL_LENGTH('dbo.APP_TITULO','TITULO_MARCA') IS NULL ALTER TABLE dbo.APP_TITULO ADD TITULO_MARCA varchar(50) NULL;
IF COL_LENGTH('dbo.APP_TITULO','TITULO_ZONA') IS NULL ALTER TABLE dbo.APP_TITULO ADD TITULO_ZONA varchar(50) NULL;
GO

