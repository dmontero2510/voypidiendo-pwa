IF OBJECT_ID('dbo.APP_VISITAS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_VISITAS
    (
        ID_VISITA       int IDENTITY(1,1) NOT NULL,
        ID_USUARIO      int NOT NULL,
        USUARIO         varchar(50) NOT NULL,
        ORGANIZACION    int NOT NULL,
        COD_CLIENTE     int NOT NULL,
        FECHA_LLEGADA   datetime NOT NULL CONSTRAINT DF_APP_VISITAS_LLEGADA DEFAULT (GETDATE()),
        LAT_LLEGADA     decimal(10,7) NULL,
        LON_LLEGADA     decimal(10,7) NULL,
        FECHA_SALIDA    datetime NULL,
        LAT_SALIDA      decimal(10,7) NULL,
        LON_SALIDA      decimal(10,7) NULL,
        CONSTRAINT PK_APP_VISITAS PRIMARY KEY (ID_VISITA),
        CONSTRAINT FK_APP_VISITAS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES dbo.APP_USUARIOS(ID_USUARIO)
    );

    CREATE INDEX IX_APP_VISITAS_USUARIO_ACTIVA ON dbo.APP_VISITAS(ID_USUARIO, FECHA_SALIDA, FECHA_LLEGADA);
    CREATE INDEX IX_APP_VISITAS_FECHA ON dbo.APP_VISITAS(FECHA_LLEGADA);
END;
GO
