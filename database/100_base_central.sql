USE master;
GO

IF DB_ID('VOYPIDIENDO_CENTRAL') IS NULL
    CREATE DATABASE VOYPIDIENDO_CENTRAL;
GO

USE VOYPIDIENDO_CENTRAL;
GO

IF OBJECT_ID('dbo.SA_USUARIOS','U') IS NULL
BEGIN
    CREATE TABLE dbo.SA_USUARIOS
    (
        ID_USUARIO int IDENTITY(1,1) NOT NULL PRIMARY KEY,
        USUARIO varchar(50) NOT NULL,
        NOMBRE varchar(100) NOT NULL,
        CLAVE_HASH varchar(100) NOT NULL,
        HABILITADO bit NOT NULL CONSTRAINT DF_SA_USUARIOS_HABILITADO DEFAULT(1),
        FECHA_ALTA datetime2(0) NOT NULL CONSTRAINT DF_SA_USUARIOS_FECHA DEFAULT(SYSDATETIME()),
        ULTIMO_ACCESO datetime2(0) NULL,
        CONSTRAINT UQ_SA_USUARIOS_USUARIO UNIQUE(USUARIO)
    );
END;
GO

IF OBJECT_ID('dbo.SA_EMPRESAS','U') IS NULL
BEGIN
    CREATE TABLE dbo.SA_EMPRESAS
    (
        ID_EMPRESA int IDENTITY(1,1) NOT NULL PRIMARY KEY,
        CODIGO varchar(40) NOT NULL,
        NOMBRE varchar(120) NOT NULL,
        TITULO varchar(80) NOT NULL,
        SUBTITULO varchar(150) NULL,
        LOGO_URL varchar(300) NULL,
        COLOR_PRINCIPAL varchar(20) NOT NULL CONSTRAINT DF_SA_EMPRESAS_COLOR1 DEFAULT('#20b3df'),
        COLOR_SECUNDARIO varchar(20) NOT NULL CONSTRAINT DF_SA_EMPRESAS_COLOR2 DEFAULT('#10213c'),
        CONEXION_CIFRADA varbinary(max) NULL,
        CONEXION_REFERENCIA varchar(150) NULL,
        PERCEP_IIBB bit NOT NULL CONSTRAINT DF_SA_EMPRESAS_PERCEP DEFAULT(1),
        SUBTOTALES bit NOT NULL CONSTRAINT DF_SA_EMPRESAS_SUBTOTALES DEFAULT(1),
        HABILITADA bit NOT NULL CONSTRAINT DF_SA_EMPRESAS_HABILITADA DEFAULT(1),
        FECHA_ALTA datetime2(0) NOT NULL CONSTRAINT DF_SA_EMPRESAS_FECHA DEFAULT(SYSDATETIME()),
        VENCIMIENTO date NULL,
        ULTIMA_ACTIVIDAD datetime2(0) NULL,
        CONSTRAINT UQ_SA_EMPRESAS_CODIGO UNIQUE(CODIGO)
    );
END;
GO

IF OBJECT_ID('dbo.SA_DOMINIOS','U') IS NULL
BEGIN
    CREATE TABLE dbo.SA_DOMINIOS
    (
        ID_DOMINIO int IDENTITY(1,1) NOT NULL PRIMARY KEY,
        ID_EMPRESA int NOT NULL,
        DOMINIO varchar(200) NOT NULL,
        PRINCIPAL bit NOT NULL CONSTRAINT DF_SA_DOMINIOS_PRINCIPAL DEFAULT(0),
        HABILITADO bit NOT NULL CONSTRAINT DF_SA_DOMINIOS_HABILITADO DEFAULT(1),
        CONSTRAINT FK_SA_DOMINIOS_EMPRESA FOREIGN KEY(ID_EMPRESA) REFERENCES dbo.SA_EMPRESAS(ID_EMPRESA),
        CONSTRAINT UQ_SA_DOMINIOS_DOMINIO UNIQUE(DOMINIO)
    );
END;
GO

IF OBJECT_ID('dbo.SA_FUNCIONES','U') IS NULL
BEGIN
    CREATE TABLE dbo.SA_FUNCIONES
    (
        ID_EMPRESA int NOT NULL,
        FUNCION varchar(60) NOT NULL,
        HABILITADA bit NOT NULL,
        CONSTRAINT PK_SA_FUNCIONES PRIMARY KEY(ID_EMPRESA,FUNCION),
        CONSTRAINT FK_SA_FUNCIONES_EMPRESA FOREIGN KEY(ID_EMPRESA) REFERENCES dbo.SA_EMPRESAS(ID_EMPRESA)
    );
END;
GO

IF OBJECT_ID('dbo.SA_AUDITORIA','U') IS NULL
BEGIN
    CREATE TABLE dbo.SA_AUDITORIA
    (
        ID_AUDITORIA bigint IDENTITY(1,1) NOT NULL PRIMARY KEY,
        FECHA datetime2(0) NOT NULL CONSTRAINT DF_SA_AUDITORIA_FECHA DEFAULT(SYSDATETIME()),
        ID_USUARIO int NULL,
        ID_EMPRESA int NULL,
        ACCION varchar(80) NOT NULL,
        DETALLE varchar(1000) NULL,
        IP varchar(60) NULL,
        CONSTRAINT FK_SA_AUDITORIA_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES dbo.SA_USUARIOS(ID_USUARIO),
        CONSTRAINT FK_SA_AUDITORIA_EMPRESA FOREIGN KEY(ID_EMPRESA) REFERENCES dbo.SA_EMPRESAS(ID_EMPRESA)
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.SA_AUDITORIA') AND name='IX_SA_AUDITORIA_FECHA')
    CREATE INDEX IX_SA_AUDITORIA_FECHA ON dbo.SA_AUDITORIA(FECHA DESC);
GO
